#!/usr/bin/env node

import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(root, '.env.maps.local');
const supportedNames = new Set([
  'GOOGLE_MAPS_API_KEY',
  'GOOGLE_MAPS_WEB_KEY',
  'GOOGLE_MAPS_IOS_KEY',
  'GOOGLE_MAPS_ANDROID_KEY',
]);

// Parse data only. Never evaluate or source this file in a shell.
function parseLocalKeys(content) {
  const values = new Map();
  for (const [index, originalLine] of content.split(/\r?\n/).entries()) {
    const line = originalLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = /^(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (!match || !supportedNames.has(match[1])) {
      throw new Error(`Unsupported setting on line ${index + 1} of .env.maps.local.`);
    }
    const name = match[1];
    let value = match[2];
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (values.has(name)) throw new Error(`Duplicate setting ${name}.`);
    if (value && !/^AIza[A-Za-z0-9_-]{35}$/.test(value)) {
      throw new Error(`${name} must contain a valid Google API key format.`);
    }
    values.set(name, value);
  }
  return values;
}

async function writePrivate(relativePath, content) {
  const path = resolve(root, relativePath);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content, { mode: 0o600 });
  await chmod(path, 0o600);
}

try {
  const settings = parseLocalKeys(await readFile(input, 'utf8'));
  await chmod(input, 0o600);
  const fallback = settings.get('GOOGLE_MAPS_API_KEY') ?? '';
  const keys = {
    web: settings.get('GOOGLE_MAPS_WEB_KEY') || fallback,
    ios: settings.get('GOOGLE_MAPS_IOS_KEY') || fallback,
    android: settings.get('GOOGLE_MAPS_ANDROID_KEY') || fallback,
  };
  if (Object.values(keys).some((value) => !value)) {
    throw new Error('Set GOOGLE_MAPS_API_KEY or provide all three platform keys in .env.maps.local.');
  }

  await writePrivate('app/ios/Flutter/Maps.local.xcconfig',
    `// Generated by scripts/configure-maps.mjs. Keep this file private.\nGOOGLE_MAPS_API_KEY=${keys.ios}\n`);
  await writePrivate('app/android/maps.local.properties',
    `# Generated by scripts/configure-maps.mjs. Keep this file private.\nGOOGLE_MAPS_API_KEY=${keys.android}\n`);
  for (const [platform, key] of Object.entries(keys)) {
    await writePrivate(`app/.maps-${platform}.local.json`, `${JSON.stringify({
      MAP_PROVIDER: 'google',
      GOOGLE_MAPS_API_KEY: key,
    }, null, 2)}\n`);
  }
  console.log('Google Maps local configuration generated for web, iOS and Android. API keys were not printed.');
} catch (error) {
  // Filesystem errors include paths, but never file contents or keys.
  console.error(error instanceof Error ? error.message : 'Could not configure Google Maps.');
  process.exitCode = 1;
}
